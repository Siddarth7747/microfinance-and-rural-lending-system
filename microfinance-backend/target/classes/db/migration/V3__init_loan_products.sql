CREATE TABLE IF NOT EXISTS loan_products (
    id BIGSERIAL PRIMARY KEY,
    product_code VARCHAR(20) NOT NULL UNIQUE,
    product_name VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    interest_method VARCHAR(30) NOT NULL,
    interest_rate_per_annum NUMERIC(5, 2) NOT NULL,
    min_loan_amount NUMERIC(12, 2) NOT NULL,
    max_loan_amount NUMERIC(12, 2) NOT NULL,
    min_tenure_months INT NOT NULL,
    max_tenure_months INT NOT NULL,
    repayment_frequency VARCHAR(20) NOT NULL,
    grace_period_days INT,
    processing_fee_percent NUMERIC(5, 2),
    processing_fee_flat NUMERIC(12, 2),
    insurance_premium_percent NUMERIC(5, 2),
    penal_interest_rate NUMERIC(5, 2),
    min_group_size INT,
    max_group_size INT,
    min_cibil_score INT,
    max_existing_loan_outstanding NUMERIC(12, 2),
    max_existing_loans INT,
    min_annual_income NUMERIC(12, 2),
    min_age INT,
    max_age INT,
    requires_grt BOOLEAN NOT NULL DEFAULT TRUE,
    requires_cibil_check BOOLEAN NOT NULL DEFAULT TRUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP,
    updated_at TIMESTAMP
);
