CREATE TABLE IF NOT EXISTS repayment_transactions (
    id BIGSERIAL PRIMARY KEY,
    transaction_id VARCHAR(30) NOT NULL UNIQUE,
    loan_id BIGINT NOT NULL,
    borrower_id BIGINT NOT NULL,
    emi_schedule_id BIGINT,
    amount NUMERIC(12, 2) NOT NULL,
    principal_paid NUMERIC(12, 2),
    interest_paid NUMERIC(12, 2),
    penal_interest_paid NUMERIC(12, 2),
    excess_amount NUMERIC(12, 2),
    payment_mode VARCHAR(20) NOT NULL,
    payment_date DATE NOT NULL,
    reference_number VARCHAR(50),
    collected_by VARCHAR(100),
    collection_latitude DOUBLE PRECISION,
    collection_longitude DOUBLE PRECISION,
    receipt_photo_url VARCHAR(500),
    is_offline_entry BOOLEAN NOT NULL DEFAULT FALSE,
    synced_at TIMESTAMP,
    is_reversed BOOLEAN NOT NULL DEFAULT FALSE,
    reversal_reason VARCHAR(255),
    branch_id BIGINT,
    created_at TIMESTAMP
);
