CREATE TABLE IF NOT EXISTS borrowers (
    id BIGSERIAL PRIMARY KEY,
    brn VARCHAR(20) NOT NULL UNIQUE,
    first_name VARCHAR(100) NOT NULL,
    middle_name VARCHAR(100),
    last_name VARCHAR(100) NOT NULL,
    date_of_birth DATE NOT NULL,
    gender VARCHAR(10) NOT NULL,
    aadhaar_number VARCHAR(12) NOT NULL,
    pan_number VARCHAR(10),
    voter_id VARCHAR(20),
    mobile_number VARCHAR(15) NOT NULL,
    alternate_mobile VARCHAR(15),
    email VARCHAR(255),
    address_line1 VARCHAR(255) NOT NULL,
    address_line2 VARCHAR(255),
    village VARCHAR(100) NOT NULL,
    taluka VARCHAR(100) NOT NULL,
    district VARCHAR(100) NOT NULL,
    state VARCHAR(100) NOT NULL,
    pincode VARCHAR(6) NOT NULL,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    father_or_spouse_name VARCHAR(100),
    family_size INT,
    annual_household_income NUMERIC(12, 2),
    occupation VARCHAR(100),
    caste VARCHAR(50),
    religion VARCHAR(50),
    bank_name VARCHAR(100),
    bank_account_number VARCHAR(20),
    ifsc_code VARCHAR(11),
    kyc_status VARCHAR(30) NOT NULL,
    photo_url VARCHAR(500),
    signature_url VARCHAR(500),
    cibil_score INT,
    cibil_fetch_date DATE,
    existing_loan_outstanding NUMERIC(12, 2),
    number_of_existing_loans INT,
    branch_id BIGINT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(100),
    modified_by VARCHAR(100)
);
