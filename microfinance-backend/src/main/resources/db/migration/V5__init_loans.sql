CREATE TABLE IF NOT EXISTS loans (
    id BIGSERIAL PRIMARY KEY,
    loan_account_number VARCHAR(30) NOT NULL UNIQUE,
    loan_application_id BIGINT NOT NULL,
    borrower_id BIGINT NOT NULL,
    loan_product_id BIGINT NOT NULL,
    loan_group_id BIGINT,
    sanctioned_amount NUMERIC(12, 2) NOT NULL,
    disbursed_amount NUMERIC(12, 2) NOT NULL,
    outstanding_principal NUMERIC(12, 2) NOT NULL,
    outstanding_interest NUMERIC(12, 2) NOT NULL,
    overdue_amount NUMERIC(12, 2),
    interest_rate NUMERIC(5, 2) NOT NULL,
    tenure_months INT NOT NULL,
    emi_amount NUMERIC(12, 2) NOT NULL,
    total_emis INT,
    paid_emis INT,
    status VARCHAR(30) NOT NULL,
    par_classification VARCHAR(30),
    dpd INT,
    disbursement_date DATE,
    first_emi_date DATE,
    last_emi_date DATE,
    maturity_date DATE,
    closure_date DATE,
    processing_fee NUMERIC(12, 2),
    insurance_premium NUMERIC(12, 2),
    total_repaid NUMERIC(12, 2),
    penal_interest_accrued NUMERIC(12, 2),
    branch_id BIGINT,
    assigned_officer VARCHAR(100),
    is_restructured BOOLEAN NOT NULL DEFAULT FALSE,
    is_written_off BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP,
    updated_at TIMESTAMP
);
