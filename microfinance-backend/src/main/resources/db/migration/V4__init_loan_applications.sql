CREATE TABLE IF NOT EXISTS loan_applications (
    id BIGSERIAL PRIMARY KEY,
    application_number VARCHAR(30) NOT NULL UNIQUE,
    borrower_id BIGINT NOT NULL,
    loan_product_id BIGINT NOT NULL,
    loan_group_id BIGINT,
    requested_amount NUMERIC(12, 2) NOT NULL,
    approved_amount NUMERIC(12, 2),
    requested_tenure_months INT NOT NULL,
    approved_tenure_months INT,
    loan_purpose VARCHAR(255) NOT NULL,
    status VARCHAR(30) NOT NULL,
    field_officer_name VARCHAR(100),
    field_officer_remarks VARCHAR(500),
    field_officer_recommendation_date DATE,
    branch_manager_name VARCHAR(100),
    branch_manager_remarks VARCHAR(500),
    branch_manager_approval_date DATE,
    credit_committee_approver VARCHAR(100),
    credit_committee_remarks VARCHAR(500),
    credit_committee_approval_date DATE,
    rejection_reason VARCHAR(500),
    rejection_date DATE,
    signed_agreement_url VARCHAR(500),
    bureau_check_completed BOOLEAN DEFAULT FALSE,
    branch_id BIGINT,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(100)
);
